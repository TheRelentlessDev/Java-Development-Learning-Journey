public class Factorial {
    public static void main(String[] args) {
        for(int i = 1; i <=20 ; i++){
            if( i % 3 == 0){
                System.out.println( i +" is a multiple of 3");
            }else{
                System.out.println(i + " is not a multiple of 3");
            }
        }
    }
}
